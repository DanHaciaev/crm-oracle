-- ============================================================
-- Deliveries / trips (CRM-only)
-- ============================================================
-- DIPP FRUICT knows the vehicles (AGRO_VEHICLES) and which vehicle a sales
-- document left on, but has no trips or delivery statuses. A trip is one
-- vehicle run with a driver and a list of stops; each stop is one sales
-- document. The CRM never writes to AGRO_SALES_DOCS — the trip only refers
-- to it. A sales document can be in at most one trip that isn't cancelled
-- (checked in code, so cancelled trips keep their stops for history).
-- Oracle 11g: sequences + BEFORE INSERT triggers. Idempotent.

DECLARE v INT;
BEGIN
  SELECT COUNT(*) INTO v FROM USER_TABLES WHERE TABLE_NAME = 'AGRO_CRM_TRIPS';
  IF v = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE AGRO_CRM_TRIPS (
        ID            NUMBER         NOT NULL,
        TRIP_NUMBER   VARCHAR2(30)   NOT NULL,
        TRIP_DATE     DATE           NOT NULL,
        VEHICLE_ID    NUMBER,
        CARRIER_NAME  VARCHAR2(200),
        DRIVER_NAME   VARCHAR2(200),
        DRIVER_PHONE  VARCHAR2(50),
        DESTINATION   VARCHAR2(300),
        STATUS        VARCHAR2(15)   DEFAULT ''planned'' NOT NULL,
        DEPARTED_AT   DATE,
        ARRIVED_AT    DATE,
        COST_AMOUNT   NUMBER(14,2),
        COST_CURRENCY VARCHAR2(3),
        NOTES         VARCHAR2(1000),
        CREATED_BY    VARCHAR2(100),
        CREATED_AT    DATE DEFAULT SYSDATE NOT NULL,
        UPDATED_AT    DATE,
        CONSTRAINT PK_AGRO_CRM_TRIPS PRIMARY KEY (ID),
        CONSTRAINT UQ_AGRO_CRM_TRIPS_NO UNIQUE (TRIP_NUMBER),
        CONSTRAINT FK_AGRO_CRM_TRIP_VEH FOREIGN KEY (VEHICLE_ID) REFERENCES AGRO_VEHICLES (ID),
        CONSTRAINT CK_AGRO_CRM_TRIP_ST CHECK (STATUS IN (''planned'',''loading'',''in_transit'',''delivered'',''cancelled'')),
        CONSTRAINT CK_AGRO_CRM_TRIP_COST CHECK (COST_AMOUNT IS NULL OR COST_AMOUNT >= 0)
      )';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AGRO_CRM_TRIP_DATE ON AGRO_CRM_TRIPS (TRIP_DATE)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AGRO_CRM_TRIP_VEH ON AGRO_CRM_TRIPS (VEHICLE_ID)';
  END IF;
  SELECT COUNT(*) INTO v FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'AGRO_CRM_TRIPS_SEQ';
  IF v = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE AGRO_CRM_TRIPS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
  END IF;

  SELECT COUNT(*) INTO v FROM USER_TABLES WHERE TABLE_NAME = 'AGRO_CRM_TRIP_STOPS';
  IF v = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE AGRO_CRM_TRIP_STOPS (
        ID            NUMBER         NOT NULL,
        TRIP_ID       NUMBER         NOT NULL,
        SALES_DOC_ID  NUMBER         NOT NULL,
        STOP_ORDER    NUMBER(3)      DEFAULT 1 NOT NULL,
        ADDRESS       VARCHAR2(500),
        STATUS        VARCHAR2(10)   DEFAULT ''pending'' NOT NULL,
        DELIVERED_AT  DATE,
        RECEIVED_BY   VARCHAR2(200),
        NOTES         VARCHAR2(1000),
        CONSTRAINT PK_AGRO_CRM_TRIP_STOPS PRIMARY KEY (ID),
        CONSTRAINT UQ_AGRO_CRM_STOP_DOC UNIQUE (TRIP_ID, SALES_DOC_ID),
        CONSTRAINT FK_AGRO_CRM_STOP_TRIP FOREIGN KEY (TRIP_ID) REFERENCES AGRO_CRM_TRIPS (ID),
        CONSTRAINT FK_AGRO_CRM_STOP_SALE FOREIGN KEY (SALES_DOC_ID) REFERENCES AGRO_SALES_DOCS (ID),
        CONSTRAINT CK_AGRO_CRM_STOP_ST CHECK (STATUS IN (''pending'',''delivered'',''failed''))
      )';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AGRO_CRM_STOP_SALE ON AGRO_CRM_TRIP_STOPS (SALES_DOC_ID)';
  END IF;
  SELECT COUNT(*) INTO v FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'AGRO_CRM_TRIP_STOPS_SEQ';
  IF v = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE AGRO_CRM_TRIP_STOPS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
  END IF;
END;
/

CREATE OR REPLACE TRIGGER AGRO_CRM_TRIPS_BI
BEFORE INSERT ON AGRO_CRM_TRIPS FOR EACH ROW
BEGIN
  IF :NEW.ID IS NULL THEN
    SELECT AGRO_CRM_TRIPS_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
  END IF;
END;
/

CREATE OR REPLACE TRIGGER AGRO_CRM_TRIP_STOPS_BI
BEFORE INSERT ON AGRO_CRM_TRIP_STOPS FOR EACH ROW
BEGIN
  IF :NEW.ID IS NULL THEN
    SELECT AGRO_CRM_TRIP_STOPS_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
  END IF;
END;
/
