-- ============================================================
-- Commercial offers / quotes (CRM-only)
-- ============================================================
-- A quote goes to a customer (AGRO_CUSTOMERS) and/or a deal (a lead in
-- AGRO_CRM_LEADS — the CRM's pipeline). CLIENT_NAME keeps the addressee for
-- a lead that isn't a customer yet. Lines are free text with an optional
-- item from AGRO_ITEMS; prices are per kg in the quote currency. Quotes are
-- never deleted — they end as accepted / rejected. "Expired" is not stored:
-- a sent quote past VALID_UNTIL is shown as expired.
-- Oracle 11g: sequences + BEFORE INSERT triggers. Idempotent.

DECLARE v INT;
BEGIN
  SELECT COUNT(*) INTO v FROM USER_TABLES WHERE TABLE_NAME = 'AGRO_CRM_QUOTES';
  IF v = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE AGRO_CRM_QUOTES (
        ID              NUMBER         NOT NULL,
        QUOTE_NUMBER    VARCHAR2(30)   NOT NULL,
        QUOTE_DATE      DATE           NOT NULL,
        VALID_UNTIL     DATE,
        CUSTOMER_ID     NUMBER,
        LEAD_ID         NUMBER,
        CLIENT_NAME     VARCHAR2(300)  NOT NULL,
        CONTACT_PERSON  VARCHAR2(200),
        CURRENCY_CODE   VARCHAR2(3)    NOT NULL,
        DELIVERY_TERMS  VARCHAR2(300),
        PAYMENT_TERMS   VARCHAR2(300),
        NOTES           VARCHAR2(2000),
        INTERNAL_NOTES  VARCHAR2(1000),
        DISCOUNT_PCT    NUMBER(5,2)    DEFAULT 0 NOT NULL,
        SUBTOTAL        NUMBER(14,2)   DEFAULT 0 NOT NULL,
        DISCOUNT_AMOUNT NUMBER(14,2)   DEFAULT 0 NOT NULL,
        TOTAL           NUMBER(14,2)   DEFAULT 0 NOT NULL,
        STATUS          VARCHAR2(10)   DEFAULT ''draft'' NOT NULL,
        MANAGER         VARCHAR2(100),
        SENT_AT         DATE,
        DECIDED_AT      DATE,
        REJECT_REASON   VARCHAR2(500),
        CREATED_BY      VARCHAR2(100),
        CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
        UPDATED_AT      DATE,
        CONSTRAINT PK_AGRO_CRM_QUOTES PRIMARY KEY (ID),
        CONSTRAINT UQ_AGRO_CRM_QUOTES_NO UNIQUE (QUOTE_NUMBER),
        CONSTRAINT FK_AGRO_CRM_QT_CUST FOREIGN KEY (CUSTOMER_ID) REFERENCES AGRO_CUSTOMERS (ID),
        CONSTRAINT FK_AGRO_CRM_QT_LEAD FOREIGN KEY (LEAD_ID) REFERENCES AGRO_CRM_LEADS (ID),
        CONSTRAINT CK_AGRO_CRM_QT_ST CHECK (STATUS IN (''draft'',''sent'',''accepted'',''rejected'')),
        CONSTRAINT CK_AGRO_CRM_QT_DISC CHECK (DISCOUNT_PCT >= 0 AND DISCOUNT_PCT <= 100)
      )';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AGRO_CRM_QT_CUST ON AGRO_CRM_QUOTES (CUSTOMER_ID)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AGRO_CRM_QT_LEAD ON AGRO_CRM_QUOTES (LEAD_ID)';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AGRO_CRM_QT_DATE ON AGRO_CRM_QUOTES (QUOTE_DATE)';
  END IF;
  SELECT COUNT(*) INTO v FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'AGRO_CRM_QUOTES_SEQ';
  IF v = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE AGRO_CRM_QUOTES_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
  END IF;

  SELECT COUNT(*) INTO v FROM USER_TABLES WHERE TABLE_NAME = 'AGRO_CRM_QUOTE_LINES';
  IF v = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE AGRO_CRM_QUOTE_LINES (
        ID            NUMBER         NOT NULL,
        QUOTE_ID      NUMBER         NOT NULL,
        LINE_ORDER    NUMBER(3)      NOT NULL,
        ITEM_ID       NUMBER,
        DESCRIPTION   VARCHAR2(300)  NOT NULL,
        PACKAGING     VARCHAR2(200),
        QTY_KG        NUMBER(14,3)   NOT NULL,
        PRICE_PER_KG  NUMBER(14,4)   NOT NULL,
        AMOUNT        NUMBER(14,2)   NOT NULL,
        CONSTRAINT PK_AGRO_CRM_QUOTE_LINES PRIMARY KEY (ID),
        CONSTRAINT FK_AGRO_CRM_QL_QUOTE FOREIGN KEY (QUOTE_ID) REFERENCES AGRO_CRM_QUOTES (ID),
        CONSTRAINT FK_AGRO_CRM_QL_ITEM FOREIGN KEY (ITEM_ID) REFERENCES AGRO_ITEMS (ID),
        CONSTRAINT CK_AGRO_CRM_QL_QTY CHECK (QTY_KG > 0 AND PRICE_PER_KG >= 0)
      )';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_AGRO_CRM_QL_QUOTE ON AGRO_CRM_QUOTE_LINES (QUOTE_ID)';
  END IF;
  SELECT COUNT(*) INTO v FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'AGRO_CRM_QUOTE_LINES_SEQ';
  IF v = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE AGRO_CRM_QUOTE_LINES_SEQ START WITH 1 INCREMENT BY 1 NOCACHE';
  END IF;
END;
/

CREATE OR REPLACE TRIGGER AGRO_CRM_QUOTES_BI
BEFORE INSERT ON AGRO_CRM_QUOTES FOR EACH ROW
BEGIN
  IF :NEW.ID IS NULL THEN
    SELECT AGRO_CRM_QUOTES_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
  END IF;
END;
/

CREATE OR REPLACE TRIGGER AGRO_CRM_QUOTE_LINES_BI
BEFORE INSERT ON AGRO_CRM_QUOTE_LINES FOR EACH ROW
BEGIN
  IF :NEW.ID IS NULL THEN
    SELECT AGRO_CRM_QUOTE_LINES_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
  END IF;
END;
/
